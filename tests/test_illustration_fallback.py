def decision(**patch):
    return {'basis':'low_similarity','reference':'input/slide-001.png','drawing':'assets/drawing.svg',
            'similarity_pct':72,'reason':'TEST Agent judgment: outline and proportions differ',**patch}


@pytest.mark.parametrize('score',[0, 72, 74.999])
def test_strictly_below_threshold_is_allowed(score):
    assert validate_decision(decision(similarity_pct=score))['similarity_pct']==score


@pytest.mark.parametrize('score',[75,75.001,100,-1,True,None,'72',float('nan'),float('inf'),10**400])
def test_threshold_and_invalid_scores_are_rejected(score):
    with pytest.raises(ValueError):validate_decision(decision(similarity_pct=score))


def test_user_request_can_skip_drawing_but_requires_reference_and_reason():
    data={'basis':'user_request','reference':'input/reference.png','reason':'User explicitly asked for generated icons'}
