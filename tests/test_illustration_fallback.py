def test_active_material_failure_is_shown_without_changing_completed_route_nodes():
    route={'id':'job','purpose':'test','decision':decision(),'status':'pending','multi_icon_sheet':True,'placed':0,'cropped':0,'task_id':'material-task'}
    failure={'id':'failed','status':'outcome_unknown','tool':'workflow.submit','task_id':'material-task','evidence_id':'audit-test'}
    state={'activity':{'generation_routes':[route],'calls':[failure],'issues':reconcile([], [failure])}}
    nodes=graph(state)['nodes']
    assert sum(n['status']=='outcome_unknown' for n in nodes)==1
    assert next(n for n in nodes if n.get('route_job') and n['kind']=='generation')['status']=='outcome_unknown'
    assert next(n for n in nodes if n.get('kind')=='fidelity')['status']=='done'
    assert step_kind('workflow.submit','asset_material')=='generation'
    assert step_kind('assets.crop')=='crop'


