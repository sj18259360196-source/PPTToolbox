def make_project(tmp_path):
    p=tmp_path/'project';wf.start(p,[ref(tmp_path)])
    respond(p,{'regions':[{'id':'art','bbox':[0,0,640,360],'role':'diagram','summary':'SYNTHETIC illustration fixture'}]})
    (p/'assets').mkdir(exist_ok=True)
    (p/'assets/drawing.svg').write_text('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="50"><rect width="45" height="45" fill="red"/></svg>','utf-8')
    return p


def request(data=None, **patch):
    return {'action':'request_asset','request':{'id':'artwork','purpose':'SYNTHETIC pair of icons',
        'prompt':'Reference guided separate icons with transparent gutters, no labels',
        'transparent':True,'allowed_approximation':True,'multi_icon_sheet':True,
        'generation_decision':decision() if data is None else data,**patch}}


def projection(p):
    state=load(p)
    return {'phase':{'stage':'production','status':'running'},
            'activity':{'generation_routes':generation_routes(state),'calls':[]}}


def test_request_validation_is_atomic_and_requires_real_drawing(tmp_path):
    p=make_project(tmp_path);task=wf.next_task(p)
    for data in [decision(similarity_pct=75),decision(drawing='assets/missing.svg')]:
        with pytest.raises(WorkflowError):respond(p,request(data),task)
        assert load(p)['asset_jobs']==[]
        assert wf.next_task(p)['task']['id']==task['task']['id']
    with pytest.raises(WorkflowError):respond(p,request(transparent=False),task)
    assert not load(p)['asset_jobs']


